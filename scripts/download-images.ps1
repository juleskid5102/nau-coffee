$outDir = "e:\Antigravity IDE\projects\nau-coffee\customer\public\images"

$success = 0
$fail = 0

foreach ($entry in $images.GetEnumerator()) {
  $name = $entry.Key
  $url = $entry.Value
  $outFile = Join-Path $outDir "$name.jpg"
  
  Write-Host "Downloading $name..." -NoNewline
  try {
    Invoke-WebRequest -Uri $url -OutFile $outFile -TimeoutSec 15 -ErrorAction Stop
    $size = (Get-Item $outFile).Length
    if ($size -gt 1000) {
      Write-Host " OK ($size bytes)" -ForegroundColor Green
      $success++
    } else {
      Write-Host " TOO SMALL ($size bytes)" -ForegroundColor Yellow
      Remove-Item $outFile -ErrorAction SilentlyContinue
      $fail++
    }
  } catch {
    Write-Host " FAILED: $($_.Exception.Message)" -ForegroundColor Red
    $fail++
  }
}

Write-Host "`nResults: $success OK, $fail FAILED"
